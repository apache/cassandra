/*
 * Tests generated by an LLM and only skimmed by me (AY). Feel free to destroy them
 * if they get in your way.
 */
public class ClusterSafeVersionSerializationTest extends CassandraTestBase
{
    private static final VersionedSerializer<Integer> VERSION_DEPENDENT = new VersionedSerializer<>()
    {
        @Override
        public void serialize(Integer value, DataOutputPlus out, Version version) throws IOException
        {
            out.writeInt(value);
            if (version.isAtLeast(Version.V2))
                out.writeLong(value);
        }

        @Override
        public Integer deserialize(DataInputPlus in, Version version) throws IOException
        {
            int value = in.readInt();
            if (version.isAtLeast(Version.V2))
                in.readLong();
            return value;
        }

        @Override
        public long serializedSize(Integer value, Version version)
        {
            return version.isAtLeast(Version.V2) ? 12 : 4;
        }
    };

    private Version originalClusterSafeVersion;

    @BeforeClass
    public static void setUpClass()
    {
        DatabaseDescriptor.daemonInitialization();
        ClusterMetadataTestHelper.setInstanceForTest();
    }

    @Before
    public void rememberClusterSafeVersion()
    {
        originalClusterSafeVersion = Version.getClusterSafeVersion();
    }

    @After
    public void restoreClusterSafeVersion()
    {
        Version.setClusterSafeVersion(originalClusterSafeVersion);
    }

    @Test
    public void embeddedSerializerKeepsVersionItWasCreatedWith() throws IOException
    {
        Version.setClusterSafeVersion(Version.V1);
        IVersionedAsymmetricSerializer<Integer, Integer> createdAtV1 = mtEmbedded(VERSION_DEPENDENT);

        long size = createdAtV1.serializedSize(42, MessagingService.current_version);
        Version.setClusterSafeVersion(Version.V2);
        byte[] bytes = serialize(createdAtV1, 42);

        assertThat(bytes).hasSize((int) size);
        assertThat(bytes[0]).isEqualTo((byte) Version.V1.version());

        IVersionedAsymmetricSerializer<Integer, Integer> createdAtV2 = mtEmbedded(VERSION_DEPENDENT);
        byte[] v2Bytes = serialize(createdAtV2, 42);
        assertThat(v2Bytes).hasSize((int) createdAtV2.serializedSize(42, MessagingService.current_version));
        assertThat(v2Bytes[0]).isEqualTo((byte) Version.V2.version());
    }

    @Test
    public void messageKeepsVersionItWasCreatedWith() throws IOException
    {
        Version.setClusterSafeVersion(Version.V1);
        Message<ActivationRequest> createdAtV1 = Message.out(Verb.MT_TRANSFER_ACTIVATE_REQ, activationRequest());
        int size = createdAtV1.serializedSize(MessagingService.current_version);

        Version.setClusterSafeVersion(Version.V2);
        try (DataOutputBuffer out = new DataOutputBuffer())
        {
            Message.serializer.serialize(createdAtV1, out, MessagingService.current_version);
            assertThat(out.getLength()).isEqualTo(size);
        }

        Message<ActivationRequest> createdAtV2 = Message.out(Verb.MT_TRANSFER_ACTIVATE_REQ, activationRequest());
        try (DataOutputBuffer out = new DataOutputBuffer())
        {
            Message.serializer.serialize(createdAtV2, out, MessagingService.current_version);
            assertThat(out.getLength()).isEqualTo(createdAtV2.serializedSize(MessagingService.current_version));
        }
    }

    private static byte[] serialize(IVersionedAsymmetricSerializer<Integer, Integer> serializer, int value) throws IOException
    {
        try (DataOutputBuffer out = new DataOutputBuffer())
        {
            serializer.serialize(value, out, MessagingService.current_version);
            return out.toByteArray();
        }
    }

    private static ActivationRequest activationRequest() throws IOException
    {
        Pair<InetAddressAndPort, InetAddressAndPort> pair = Pair.create(InetAddressAndPort.getByName("127.0.0.1"), InetAddressAndPort.getByName("127.0.0.2"));
        Range<Token> range = new Range<>(new ByteOrderedPartitioner.BytesToken("key1".getBytes()), new ByteOrderedPartitioner.BytesToken("key100".getBytes()));
        return new ActivationRequest(StreamOperation.IMPORT, pair, ActivationRequest.Phase.COMMIT,
                                     new ShortMutationId(1L, 100), new NodeId(1), range, 42L, "test_ks", nextTimeUUID());
    }
}
