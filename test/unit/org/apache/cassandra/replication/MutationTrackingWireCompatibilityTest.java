/**
 * Test generated by an LLM, and only skimmed by me.
 * TODO (expected): get rid of this once any live dev clusters have been upgraded to V2
 */
public class MutationTrackingWireCompatibilityTest
{
    private static final String KEYSPACE = "mtwctks";
    private static final String TABLE = "mtwctt";

    @BeforeClass
    public static void setUp()
    {
        SchemaLoader.prepareServer();
        SchemaLoader.createKeyspace(KEYSPACE, KeyspaceParams.simple(3),
                                    TableMetadata.builder(KEYSPACE, TABLE)
                                                 .addPartitionKeyColumn("pk", UTF8Type.instance)
                                                 .addClusteringColumn("ck", UTF8Type.instance)
                                                 .addRegularColumn("value", UTF8Type.instance)
                                                 .build());
    }

    @Test
    public void clusterSafeVersionDefaultsToV1()
    {
        assertThat(Version.getClusterSafeVersion()).isEqualTo(Version.V1);
        assertThat(Version.CURRENT).isEqualTo(Version.V2);
    }

    @Test
    public void forwardedWriteV1MatchesLegacyLayout() throws IOException
    {
        Mutation mutation = mutation();
        ForwardedWrite.MutationRequest request =
            new ForwardedWrite.MutationRequest(mutation, participants(1, 2), participants(3), Epoch.create(42));

        ByteBuffer actual = serialize(ForwardedWrite.serializer, request, Version.V1);
        ByteBuffer expected = legacyForwardedWrite(mutation, nodeIds(1, 2, 3));
        assertThat(actual).isEqualTo(expected);
        assertThat((long) actual.remaining()).isEqualTo(ForwardedWrite.serializer.serializedSize(request, Version.V1));
    }

    @Test
    public void forwardedWriteLegacyBytesDecodeAsV1() throws IOException
    {
        Mutation mutation = mutation();
        ByteBuffer legacy = legacyForwardedWrite(mutation, nodeIds(1, 2, 3));

        ForwardedWrite.MutationRequest decoded;
        try (DataInputBuffer in = new DataInputBuffer(legacy, true))
        {
            decoded = ForwardedWrite.serializer.deserialize(in, Version.V1);
            assertThat(in.available()).isZero();
        }

        assertThat(serialize(ForwardedWrite.serializer, decoded, Version.V1)).isEqualTo(legacy);
    }

    @Test
    public void forwardedWriteV2Roundtrip() throws IOException
    {
        ForwardedWrite.MutationRequest request =
            new ForwardedWrite.MutationRequest(mutation(), participants(1, 2), participants(3), Epoch.create(42));
        ByteBuffer bytes = serialize(ForwardedWrite.serializer, request, Version.V2);
        try (DataInputBuffer in = new DataInputBuffer(bytes.duplicate(), true))
        {
            ForwardedWrite.MutationRequest decoded = ForwardedWrite.serializer.deserialize(in, Version.V2);
            assertThat(in.available()).isZero();
            assertThat(serialize(ForwardedWrite.serializer, decoded, Version.V2)).isEqualTo(bytes);
        }
    }

    @Test
    public void embeddedForwardedWriteUsesClusterSafeVersion() throws IOException
    {
        Mutation mutation = mutation();
        ForwardedWrite.MutationRequest request =
            new ForwardedWrite.MutationRequest(mutation, participants(1, 2), participants(3), Epoch.create(42));

        ByteBuffer actual = serialize(Verb.MT_FORWARD_WRITE_REQ.serializer(), request);
        ByteBuffer legacy = legacyForwardedWrite(mutation, nodeIds(1, 2, 3));
        ByteBuffer expected = ByteBuffer.allocate(1 + legacy.remaining()).put((byte) 1).put(legacy.duplicate()).flip();
        assertThat(actual).isEqualTo(expected);
    }

    @Test
    public void broadcastLogOffsetsV1MatchesLegacyLayout() throws IOException
    {
        Range<Token> range = range("a", "m");
        List<Offsets.Immutable> offsets = offsets();
        BroadcastLogOffsets message = new BroadcastLogOffsets(KEYSPACE, 7L, range, participants(1, 2, 3), offsets, true);

        ByteBuffer actual = serialize(BroadcastLogOffsets.serializer, message, Version.V1);
        ByteBuffer expected = legacyBroadcastLogOffsets(KEYSPACE, range, offsets, true);
        assertThat(actual).isEqualTo(expected);
        assertThat((long) actual.remaining()).isEqualTo(BroadcastLogOffsets.serializer.serializedSize(message, Version.V1));

        BroadcastLogOffsets decoded;
        try (DataInputBuffer in = new DataInputBuffer(expected.duplicate(), true))
        {
            decoded = BroadcastLogOffsets.serializer.deserialize(in, Version.V1);
            assertThat(in.available()).isZero();
        }
        assertThat(serialize(BroadcastLogOffsets.serializer, decoded, Version.V1)).isEqualTo(expected);
    }

    @Test
    public void broadcastLogOffsetsV2Roundtrip() throws IOException
    {
        BroadcastLogOffsets message = new BroadcastLogOffsets(KEYSPACE, 7L, range("a", "m"), participants(1, 2, 3), offsets(), false);
        ByteBuffer bytes = serialize(BroadcastLogOffsets.serializer, message, Version.V2);
        try (DataInputBuffer in = new DataInputBuffer(bytes.duplicate(), true))
        {
            BroadcastLogOffsets decoded = BroadcastLogOffsets.serializer.deserialize(in, Version.V2);
            assertThat(in.available()).isZero();
            assertThat(serialize(BroadcastLogOffsets.serializer, decoded, Version.V2)).isEqualTo(bytes);
        }
    }

    @Test
    public void activationRequestV1MatchesLegacyLayout() throws IOException
    {
        Pair<InetAddressAndPort, InetAddressAndPort> pair = Pair.create(InetAddressAndPort.getByName("127.0.0.1"), InetAddressAndPort.getByName("127.0.0.2"));
        TimeUUID planId = nextTimeUUID();
        ShortMutationId transferId = new ShortMutationId(1L, 100);
        NodeId coordinatorId = new NodeId(1);
        Range<Token> range = range("a", "m");
        ActivationRequest request = new ActivationRequest(StreamOperation.IMPORT, pair, ActivationRequest.Phase.COMMIT,
                                                          transferId, coordinatorId, range, 42L, KEYSPACE, planId);

        ByteBuffer actual = serialize(ActivationRequest.serializer, request, Version.V1);
        ByteBuffer expected = legacyActivationRequest(request, 1);
        assertThat(actual).isEqualTo(expected);
        assertThat((long) actual.remaining()).isEqualTo(ActivationRequest.serializer.serializedSize(request, Version.V1));

        try (DataInputBuffer in = new DataInputBuffer(expected.duplicate(), true))
        {
            ActivationRequest decoded = ActivationRequest.serializer.deserialize(in, Version.V1);
            assertThat(in.available()).isZero();
            assertThat(decoded.sinceEpoch).isNull();
            assertThat(decoded.keyspace).isEqualTo(KEYSPACE);
            assertThat(decoded.range).isEqualTo(range);
            assertThat(decoded.planId).isEqualTo(planId);
        }

        try (DataInputBuffer in = new DataInputBuffer(serialize(ActivationRequest.serializer, request, Version.V2), true))
        {
            assertThat(ActivationRequest.serializer.deserialize(in, Version.V2)).isEqualTo(request);
        }
    }

    private static ByteBuffer legacyForwardedWrite(Mutation mutation, Set<NodeId> recipients) throws IOException
    {
        int messagingVersion = Version.V1.messagingVersion();
        try (DataOutputBuffer out = new DataOutputBuffer())
        {
            Mutation.serializer.serialize(mutation, out, messagingVersion);
            CollectionSerializers.serializeCollection(recipients, out, messagingVersion, NodeId.messagingSerializer);
            return out.asNewBuffer();
        }
    }

    private static ByteBuffer legacyBroadcastLogOffsets(String keyspace, Range<Token> range, List<Offsets.Immutable> offsets, boolean durable) throws IOException
    {
        try (DataOutputBuffer out = new DataOutputBuffer())
        {
            out.writeUTF(keyspace);
            AbstractBounds.tokenSerializer.serialize(range, out, Version.V1.messagingVersion());
            CollectionSerializers.serializeList(offsets, out, Offsets.serializer);
            out.writeBoolean(durable);
            return out.asNewBuffer();
        }
    }

    private static ByteBuffer legacyActivationRequest(ActivationRequest request, int phaseId) throws IOException
    {
        int messagingVersion = Version.V1.messagingVersion();
        try (DataOutputBuffer out = new DataOutputBuffer())
        {
            out.writeUTF(request.operation.getDescription());
            InetAddressAndPort.Serializer.inetAddressAndPortSerializer.serialize(request.pair.left, out, messagingVersion);
            InetAddressAndPort.Serializer.inetAddressAndPortSerializer.serialize(request.pair.right, out, messagingVersion);
            ShortMutationId.serializer.serialize(request.transferId, out);
            NodeId.messagingSerializer.serialize(request.coordinatorId, out, messagingVersion);
            out.writeByte(phaseId);
            out.writeUTF(request.keyspace);
            Range.serializer.serialize(request.range, out, null);
            TimeUUID.Serializer.nullable.serialize(request.planId, out);
            return out.asNewBuffer();
        }
    }

    private static <T> ByteBuffer serialize(VersionedSerializer<T> serializer, T t, Version version) throws IOException
    {
        try (DataOutputBuffer out = new DataOutputBuffer())
        {
            serializer.serialize(t, out, version);
            return out.asNewBuffer();
        }
    }

    private static <T> ByteBuffer serialize(IVersionedAsymmetricSerializer<T, ?> serializer, T t) throws IOException
    {
        try (DataOutputBuffer out = new DataOutputBuffer())
        {
            serializer.serialize(t, out, MessagingService.current_version);
            return out.asNewBuffer();
        }
    }

    private static Mutation mutation()
    {
        return new RowUpdateBuilder(Schema.instance.getTableMetadata(KEYSPACE, TABLE), 0, "pk")
               .clustering("ck")
               .add("value", "v")
               .build();
    }

    private static Participants participants(Integer... hosts)
    {
        return new Participants(Arrays.asList(hosts));
    }

    private static Set<NodeId> nodeIds(int... ids)
    {
        Set<NodeId> set = new LinkedHashSet<>();
        for (int id : ids)
            set.add(new NodeId(id));
        return set;
    }

    private static List<Offsets.Immutable> offsets()
    {
        return List.of(new Offsets.Immutable(new CoordinatorLogId(1, 1), new int[]{ 0, 10, 20, 30 }),
                       new Offsets.Immutable(new CoordinatorLogId(2, 5), new int[]{ 3, 4 }));
    }

    private static Range<Token> range(String left, String right)
    {
        IPartitioner partitioner = DatabaseDescriptor.getPartitioner();
        return new Range<>(partitioner.getToken(ByteBufferUtil.bytes(left)), partitioner.getToken(ByteBufferUtil.bytes(right)));
    }
}
