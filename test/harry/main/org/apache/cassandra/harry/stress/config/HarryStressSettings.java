    // ========================== Simple Option (lightweight, self-contained) ==========================

    /**
     * A lightweight option parser, modeled after cassandra-stress's OptionSimple but self-contained
     * so harry-stress doesn't depend on the stress tool module.
     */
    static class SimpleOption
    {
        final String prefix;
        final String pattern;
        final String defaultValue;
        final boolean required;
        private String value;

        SimpleOption(String prefix, String pattern, String defaultValue, boolean required)
        {
            this.prefix = prefix;
            this.pattern = pattern;
            this.defaultValue = defaultValue;
            this.required = required;
        }

        boolean accept(String param)
        {
            String lower = toLowerCaseLocalized(param);
            String lowerPrefix = toLowerCaseLocalized(prefix);

            // Flag-style option (no value, e.g. "ssl")
            if (pattern.isEmpty())
            {
                if (lower.equals(lowerPrefix))
                {
                    value = "";
                    return true;
                }
                return false;
            }

            // Key=value style
            if (lower.startsWith(lowerPrefix))
            {
                String v = param.substring(prefix.length());
                if (!v.matches(pattern))
                    throw new IllegalArgumentException("Invalid value '" + v + "' for " + prefix + "; must match " + pattern);
                value = v;
                return true;
            }
            return false;
        }

        boolean setByUser()
        {
            return value != null;
        }

        String value()
        {
            return value != null ? value : defaultValue;
        }

        boolean isValid()
        {
            return !required || value != null;
        }
    }

    // ========================== Parsing ==========================

    public static HarryStressSettings parse(String[] args)
    {
        args = repairParams(args);
        Map<String, String[]> clArgs = parseMap(args);

        if (clArgs.containsKey("-help") || clArgs.containsKey("--help") || clArgs.containsKey("-h"))
        {
            printHelp();
            System.exit(0);
        }

        Mode mode = Mode.get(clArgs);

        ClusterSettings cluster = ClusterSettings.get(clArgs, mode == Mode.STRESS);
        SchemaSettings schema = SchemaSettings.get(clArgs);
        RateSettings rate = RateSettings.get(clArgs);
        RatioSettings ratio = RatioSettings.get(clArgs);
        OpsSettings ops = OpsSettings.get(clArgs);
        RotationSettings rotation = RotationSettings.get(clArgs);
        OutputSettings output = OutputSettings.get(clArgs, mode == Mode.GENERATE_LEVELS || mode == Mode.GENERATE_LEVELLED_SSTABLES);

        if (!clArgs.isEmpty())
        {
            printHelp();
            System.out.println("Error processing command line arguments. The following were ignored:");
            for (Map.Entry<String, String[]> e : clArgs.entrySet())
            {
                System.out.print(e.getKey());
                for (String v : e.getValue())
                {
                    System.out.print(" ");
                    System.out.print(v);
                }
                System.out.println();
            }
            System.exit(1);
        }

        return new HarryStressSettings(mode, cluster, schema, rate, ratio, rotation, ops, output);
    }

    private static String[] repairParams(String[] args)
    {
        if (args.length == 0)
            return args;
        StringBuilder sb = new StringBuilder();
        boolean first = true;
        for (String arg : args)
        {
            if (!first)
                sb.append(" ");
            sb.append(arg);
            first = false;
        }
        return sb.toString()
                 .replaceAll("\\s+([,=()])", "$1")
                 .replaceAll("([,=(])\\s+", "$1")
                 .split(" +");
    }

    private static Map<String, String[]> parseMap(String[] args)
    {
        if (args.length == 0)
        {
            printHelp();
            System.exit(1);
        }
        final LinkedHashMap<String, String[]> r = new LinkedHashMap<>();
        String key = null;
        List<String> params = new ArrayList<>();
        for (int i = 0; i < args.length; i++)
        {
            if (args[i].startsWith("-"))
            {
                if (key != null)
                    putParam(key, params.toArray(new String[0]), r);
                key = toLowerCaseLocalized(args[i]);
                params.clear();
            }
            else
            {
                params.add(args[i]);
            }
        }
        if (key != null)
            putParam(key, params.toArray(new String[0]), r);
        return r;
    }

    private static void putParam(String key, String[] args, Map<String, String[]> clArgs)
    {
        String[] prev = clArgs.put(key, args);
        if (prev != null)
            throw new IllegalArgumentException(key + " is defined multiple times. Each option can be specified at most once.");
    }

