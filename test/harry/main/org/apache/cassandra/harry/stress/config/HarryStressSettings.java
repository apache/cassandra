    public enum Mode
    {
        STRESS,
        GENERATE_LEVELS,
        GENERATE_LEVELLED_SSTABLES;

        static Mode parse(String value)
        {
            switch (toLowerCaseLocalized(value))
            {
                case "stress": return STRESS;
                case "generate-levels": return GENERATE_LEVELS;
                case "generate-levelled-sstables": return GENERATE_LEVELLED_SSTABLES;
                default:
                    throw new IllegalArgumentException("Unknown mode: " + value);
            }
        }

        @Override
        public String toString()
        {
            switch (this)
            {
                case STRESS: return "stress";
                case GENERATE_LEVELS: return "generate-levels";
                case GENERATE_LEVELLED_SSTABLES: return "generate-levelled-sstables";
                default: throw new AssertionError();
            }
        }

        static Mode get(Map<String, String[]> clArgs)
        {
            String[] params = clArgs.remove("-mode");
            if (params == null || params.length == 0)
                return STRESS;
            if (params.length != 1)
                throw new IllegalArgumentException("-mode expects exactly one value: stress, generate-sstables, or generate-levels");
            return parse(params[0]);
        }

        static void printHelp()
        {
            System.out.println();
            System.out.println("Usage: -mode stress|generate-sstables|generate-levels");
            System.out.println();
            System.out.println("  stress                 Run stress test against a live cluster (default)");
            System.out.println("  generate-sstables      Generate SSTables on disk");
            System.out.println("  generate-levels        Generate token index level files");
        }
    }

